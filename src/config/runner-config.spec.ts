import { describe, expect, it } from 'vitest';
import {
  DEFAULT_RUNNER_REPOS_DIR,
  DIAGNOSIS_ENV_FILES,
  dependencyEnvironment,
  diagnosisEnvFile,
  runnerConfigFromEnv,
} from './runner-config.js';

const vectors = '{"Entrega":"processamento e entrega de campanhas"}';
const ticketEnv = {
  CLICKUP_API_TOKEN: 'token',
  CLICKUP_LIST_ID: 'list',
  DIAGNOSIS_VECTORS: vectors,
  GH_TOKEN: 'github-token',
};

describe('runnerConfigFromEnv', () => {
  it('applies defaults', () => {
    const config = runnerConfigFromEnv({}, ticketEnv);
    expect(config).toMatchObject({
      taskType: 'bug',
      taskTypeId: '1004',
      ticketTypeField: 'Tipo do ticket',
      ticketTypeValue: 'bug',
      areaField: 'Área',
      areaValues: ['EN'],
      vectorsField: 'Vetores',
      statuses: [],
      tags: [],
      includeSubtasks: true,
      createdWithinMinutes: 60,
      maxTickets: 3,
      reposDir: DEFAULT_RUNNER_REPOS_DIR,
      codexBin: 'codex',
      codexModel: undefined,
      codexTimeoutMs: 45 * 60_000,
      maxAttachments: 10,
      maxAttachmentBytes: 50 * 1024 * 1024,
      concurrency: 3,
      remediationTimeoutMs: 90 * 60_000,
      repositorySyncTimeoutMs: 5 * 60_000,
      dependencySyncEnabled: true,
      dependencySyncTimeoutMs: 30 * 60_000,
      github: { mode: 'static', token: 'github-token' },
    });
  });

  it('prefers CLI overrides for ticket window and batch size', () => {
    const config = runnerConfigFromEnv(
      { maxTickets: 7, createdWithinMinutes: 15 },
      { ...ticketEnv, CLICKUP_MAX_TICKETS: '2' },
    );
    expect(config.maxTickets).toBe(7);
    expect(config.createdWithinMinutes).toBe(15);
  });

  it('defers GitHub validation so selection-only dry runs need no credential', () => {
    const config = runnerConfigFromEnv(
      {},
      {
        CLICKUP_API_TOKEN: 'token',
        CLICKUP_LIST_ID: 'list',
        DIAGNOSIS_VECTORS: vectors,
      },
    );

    expect(config.maxTickets).toBe(3);
    expect(() => config.github).toThrow(
      'GITHUB_AUTH_MODE must be static or app',
    );
  });

  it('requires ClickUp credentials and vectors for ticket runs', () => {
    expect(() => runnerConfigFromEnv({}, {})).toThrow(
      'Missing required configuration: CLICKUP_API_TOKEN, CLICKUP_LIST_ID, DIAGNOSIS_VECTORS',
    );
  });

  it('requires only vectors for incident runs', () => {
    expect(() => runnerConfigFromEnv({ incidentId: 'inc' }, {})).toThrow(
      'Missing required configuration: DIAGNOSIS_VECTORS',
    );
    expect(
      runnerConfigFromEnv(
        { incidentId: 'inc' },
        { DIAGNOSIS_VECTORS: vectors, GH_TOKEN: 'github-token' },
      ).token,
    ).toBeUndefined();
  });

  it('rejects invalid formats', () => {
    expect(() =>
      runnerConfigFromEnv({}, { ...ticketEnv, RUNNER_CONCURRENCY: '0' }),
    ).toThrow('RUNNER_CONCURRENCY must be a positive integer');
    expect(() =>
      runnerConfigFromEnv({}, { ...ticketEnv, DEPENDENCY_SYNC_ENABLED: 'x' }),
    ).toThrow('Invalid boolean value: x');
  });
});

describe('dependencyEnvironment', () => {
  it('keeps only the allowlist and requires the private package token for service-17', () => {
    const env = { PATH: '/bin', SECRET: 's', GITHUB_DDS_TOKEN: 'dds' };
    expect(dependencyEnvironment('service-15', env)).toStrictEqual({
      PATH: '/bin',
      CI: 'true',
      HUSKY: '0',
      NODE_ENV: 'development',
    });
    expect(dependencyEnvironment('service-17', env).GITHUB_DDS_TOKEN).toBe(
      'dds',
    );
    expect(() => dependencyEnvironment('service-17', { PATH: '/bin' })).toThrow(
      'GITHUB_DDS_TOKEN is required to install service-17 private packages',
    );
  });
});

describe('diagnosisEnvFile', () => {
  const mail = DIAGNOSIS_ENV_FILES.find(({ name }) => name === 'mail')!;

  it('skips unconfigured databases and reports missing variables', () => {
    expect(diagnosisEnvFile(mail, '/repos', {})).toStrictEqual({
      name: 'mail',
      configured: false,
    });
    expect(() =>
      diagnosisEnvFile(mail, '/repos', { MAIL_POSTGRES_HOST: 'h' }),
    ).toThrow(/missing: MAIL_POSTGRES_USERNAME/);
  });

  it('renders the env file with fallbacks', () => {
    const file = diagnosisEnvFile(mail, '/repos', {
      MAIL_POSTGRES_HOST: 'h',
      MAIL_POSTGRES_USERNAME: 'u',
      MAIL_POSTGRES_PASSWORD: 'p',
      MAIL_POSTGRES_DATABASE: 'd',
    });
    expect(file).toStrictEqual({
      name: 'mail',
      configured: true,
      filename: '/repos/service-15/.env',
      content:
        '# Generated by driva-ops-agent. Do not edit.\nPOSTGRES_HOST=h\nPOSTGRES_PORT=5432\nPOSTGRES_USERNAME=u\nPOSTGRES_PASSWORD=p\nPOSTGRES_DATABASE=d\n',
    });
  });

  it('materializes the service-12 variables from the exports database credentials', () => {
    const exportService = DIAGNOSIS_ENV_FILES.find(
      ({ name }) => name === 'export',
    )!;
    expect(
      diagnosisEnvFile(exportService, '/repos', {
        INTEGRATIONS_EXPORTS_PG_HOST: 'h',
        INTEGRATIONS_EXPORTS_PG_USER: 'u',
        INTEGRATIONS_EXPORTS_PG_PASSWORD: 'p',
        INTEGRATIONS_EXPORTS_PG_DATABASE: 'd',
        DRIVA_LOGS_CH_HOST: 'ch',
      }),
    ).toStrictEqual({
      name: 'export',
      configured: true,
      filename: '/repos/service-12/.env',
      content:
        '# Generated by driva-ops-agent. Do not edit.\nPOSTGRES_HOST=h\nPOSTGRES_PORT=5432\nPOSTGRES_USER=u\nPOSTGRES_PASSWORD=p\nPOSTGRES_EXPORTS_DATABASE=d\nDRIVA_LOGS_CH_HOST=ch\n',
    });
  });

  it('does not treat shared variables as configuring a group, but still writes them', () => {
    const searchGo = DIAGNOSIS_ENV_FILES.find(
      ({ name }) => name === 'search-go',
    )!;
    const logs = { DRIVA_LOGS_CH_HOST: 'ch', DRIVA_LOGS_CH_USER: 'reader' };
    expect(diagnosisEnvFile(searchGo, '/repos', logs)).toStrictEqual({
      name: 'search-go',
      configured: false,
    });

    const file = diagnosisEnvFile(searchGo, '/repos', {
      ...logs,
      DRIVA_LIST_PG_HOST: 'h',
      DRIVA_LIST_PG_DATABASE: 'd',
      DRIVA_LIST_PG_USER: 'u',
      DRIVA_LIST_PG_PASSWORD: 'p',
    });
    expect(file).toStrictEqual({
      name: 'search-go',
      configured: true,
      filename: '/repos/service-13/.env',
      content:
        '# Generated by driva-ops-agent. Do not edit.\nPOSTGRES_BLACKLIST_HOST=h\nPOSTGRES_BLACKLIST_PORT=5432\nPOSTGRES_BLACKLIST_DATABASE=d\nPOSTGRES_BLACKLIST_USERNAME=u\nPOSTGRES_BLACKLIST_PASSWORD=p\nDRIVA_LOGS_CH_HOST=ch\nDRIVA_LOGS_CH_USER=reader\n',
    });
  });
});
